volatile uint32_t tim2_oc_count = 0U;
volatile float dbg_speed_error = 0.0f;
volatile uint32_t dbg_speed_loop_count = 0U;

void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
  if(htim->Instance == TIM3)
  {
    /* 编码器浮点角度和多圈角在这里计算（2kHz），不在 SPI 回调里做 */
    encoder_angle = (float)encoder_angle_hex * 2.0f * PI / (1 << ENCODER_BITS);

    static float encoder_angle_last = 0;
    static uint16_t ticks_last = 0;
    static int once = 1;

    /* TIM4 自由运行（约10MHz），用实际 dt 计算速度，补偿 TIM3 中断/角度更新抖动 */
    uint16_t ticks_now = (uint16_t)__HAL_TIM_GET_COUNTER(&htim4);
    uint16_t dt_ticks = ticks_now - ticks_last;
    ticks_last = ticks_now;

    if (once)
    {
      once = 0;
      encoder_angle_last = encoder_angle;   // 第一次先记录当前角度
    }

    float diff_angle = cycle_diff(encoder_angle - encoder_angle_last, 2 * PI);
    encoder_angle_last = encoder_angle;
    motor_logic_angle = cycle_diff(motor_logic_angle + diff_angle, position_cycle);

    float _motor_speed;
    if (dt_ticks > 0U)
    {
      _motor_speed = diff_angle * TIM4_TICK_HZ / (float)dt_ticks;
    }
    else
    {
      _motor_speed = motor_speed;          // 防止除零
    }

    /* 保留编码器实际速度，用于无感开环->闭环切换判据。
       原始 2kHz 编码器速度噪声很大，这里做一次轻量低通，避免噪声触发切换。 */
    encoder_speed = low_pass_filter(_motor_speed, encoder_speed, 0.1f);

    if (is_sensorless)
    {
      /* 无感：速度反馈使用 SMO 估算的电角速度，换算成机械角速度 */
      motor_speed = smo_hat_speed_e / POLE_PAIRS;

      /* 例程无感速度环按 TIM3 500Hz 运行 */
      static uint8_t sensorless_speed_div = 0;
      if (++sensorless_speed_div >= 1U)
      {
        sensorless_speed_div = 0U;

        if (speed_loop_input)
        {
          /* 无感速度给定斜坡：motor_control_context.speed 向 target 逐步靠近 */
          float ref = motor_control_context.speed;
          float target = sensorless_speed_target_norm;
          if (target > ref)
          {
            float delta = target - ref;
            ref += (delta > SENSORLESS_REF_RAMP_STEP) ? SENSORLESS_REF_RAMP_STEP : delta;
          }
          else if (target < ref)
          {
            float delta = ref - target;
            ref -= (delta > SENSORLESS_REF_RAMP_STEP) ? SENSORLESS_REF_RAMP_STEP : delta;
          }
          motor_control_context.speed = ref;

          float speed_fb_norm = motor_speed / MOTOR_MAX_SPEED;
          dbg_speed_error = *speed_loop_input - speed_fb_norm;
          dbg_speed_loop_count++;
          speed_loop_out = speed_loop(*speed_loop_input, speed_fb_norm);
        }
        else
        {
          speed_loop_out = 0.0f;
          foc_torque_cmd = 0.0f;
        }
      }
    }
    else
    {
      /* 轻量速度滤波：alpha=0.5，约 220Hz 截止，压测速毛刺但相位滞后很小 */
      motor_speed = low_pass_filter(_motor_speed, motor_speed, 0.5f);

      /* 有感：速度环 2kHz */
      if (speed_loop_input)
      {
        dbg_speed_error = *speed_loop_input - motor_speed;
        dbg_speed_loop_count++;
        speed_loop_out = speed_loop(*speed_loop_input, motor_speed);
      }
      else
      {
        speed_loop_out = 0.0f;
        foc_torque_cmd = 0.0f;
      }
    }

    static uint8_t position_div = 0;
    if (motor_control_context.type == control_type_position ||
        motor_control_context.type == control_type_position_torque ||
        motor_control_context.type == control_type_position_speed ||
        motor_control_context.type == control_type_position_speed_torque)
    {
      if (++position_div >= 2)
      {
        position_div = 0;
        position_loop_out = position_loop(motor_control_context.position, motor_logic_angle);
      }
    }
    else
    {
      position_div = 0;
      position_loop_out = 0.0f;
      foc_speed_cmd = 0.0f;
    }

    /* SPI 由 TIM2 的 OC 中断在 10kHz 触发，这里不再启动 SPI */

  }
}

